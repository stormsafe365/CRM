// Contract look for the CRM's own documents (the Addition Order, owner 11/19/26: "is there a way to make one of these
// for people moving forward through our crm ?"). The quote program (public/build/quote-builder.html) owns the contract's
// look: its CSS, the StormSafe badge, Carolina Carports' logo and the two sets of terms - CCI's verbatim "Terms,
// Conditions, and Warranties" (Rev. June 10, 2022) and StormSafe's own (CA jobs). They are local variables inside its
// printContract(), so this script reads them out of the program text and writes src/lib/contractParts.generated.js.
//
//   node scripts/gen-contract-parts.mjs          (sync-builder.mjs runs it after every program sync)
//
// tests/contractParts.test.mjs fails when the generated file no longer matches the program in public/build.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import vm from 'node:vm'

const crmRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
export const PROGRAM = resolve(crmRoot, 'public', 'build', 'quote-builder.html')
export const OUT = resolve(crmRoot, 'src', 'lib', 'contractParts.generated.js')

const ACK_CUT = '</div><div class="c-ack" style="margin-top:10px">'
const COLS = '<div class="c-tc-cols">'

/** { css, ssLogo, cciLogo, cciTerms, ssTerms } from the program's source text. Throws when a piece is not found. */
export function extractContractParts(src) {
  const L = String(src).split(/\r?\n/)
  const find = (re, from = 0) => {
    for (let i = from; i < L.length; i++) if (re.test(L[i])) return i
    throw new Error('contract parts: not found in the program: ' + re)
  }
  // the contract CSS: var CSS = ''+ ... '';  (string literals only)
  const cssStart = find(/^\s*var CSS = ''\+/, find(/^async function printContract\(/))
  let cssEnd = cssStart
  while (cssEnd < L.length && !/^\s*'';\s*$/.test(L[cssEnd])) cssEnd++
  const css = vm.runInNewContext(L.slice(cssStart, cssEnd + 1).join('\n') + '\nCSS', Object.create(null))
  // the StormSafe badge
  const lm = L[find(/^\s*var LOGO='data:image\//)].match(/'(data:image\/[^']+)'/)
  if (!lm) throw new Error('contract parts: the StormSafe logo is not a plain string')
  // Carolina Carports' logo, CCI's terms and the terms page (StormSafe's terms are its CA branch)
  const ccS = find(/^\s*var CC_LOGO='data:/)
  const p4 = find(/^\s*var page4 =/, ccS)
  const code = L.slice(ccS, p4).join('\n')
  const run = (mfr) => {
    const ctx = { ACTIVE_MFR: mfr, _delivOnly: () => false, _pickupOnly: () => false, _header: () => '', _footer: () => '', TOTAL_PAGES: 0, _cc: null }
    vm.runInNewContext(code, ctx)
    return ctx
  }
  const cci = run('CCI')
  const ca = run('CA')
  const termsOf = (page3) => {
    const a = String(page3).indexOf(COLS), b = String(page3).lastIndexOf(ACK_CUT)
    if (a < 0 || b < a) throw new Error('contract parts: the terms page changed shape')
    return String(page3).slice(a + COLS.length, b)
  }
  const parts = {
    css: String(css),
    ssLogo: lm[1],
    cciLogo: String(cci.CC_LOGO || ''),
    cciTerms: String(cci.ccTermsInner || ''),
    ssTerms: termsOf(ca.page3),
  }
  // what the documents rely on
  if (!/\.c-hdr\b/.test(parts.css) || !/\.c-tc-cols\b/.test(parts.css)) throw new Error('contract parts: the contract CSS is missing its classes')
  if (!/^data:image\/png;base64,/.test(parts.cciLogo)) throw new Error('contract parts: no Carolina Carports logo')
  if (!/Carolina Carports, Inc\./.test(parts.cciTerms) || !/Rev\. June 10, 2022/.test(parts.cciTerms)) throw new Error("contract parts: CCI's terms not found")
  if (termsOf(cci.page3) !== parts.cciTerms) throw new Error("contract parts: the CCI terms page does not print CCI's terms")
  if (!/ALL DEPOSITS AND PAYMENTS ARE NON-REFUNDABLE/.test(parts.ssTerms) || /Carolina Carports, Inc\./.test(parts.ssTerms)) throw new Error("contract parts: StormSafe's terms not found")
  return parts
}

/** The generated module's text. */
export function moduleText(parts) {
  return '// GENERATED by scripts/gen-contract-parts.mjs from public/build/quote-builder.html - do not edit by hand.\n' +
    '// The contract look of the quote program (CSS, logos, CCI terms, StormSafe terms) for the CRM\'s own documents.\n' +
    `export const CONTRACT_CSS = ${JSON.stringify(parts.css)}\n` +
    `export const SS_LOGO = ${JSON.stringify(parts.ssLogo)}\n` +
    `export const CCI_LOGO = ${JSON.stringify(parts.cciLogo)}\n` +
    `export const CCI_TERMS = ${JSON.stringify(parts.cciTerms)}\n` +
    `export const SS_TERMS = ${JSON.stringify(parts.ssTerms)}\n`
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const parts = extractContractParts(readFileSync(PROGRAM, 'utf8'))
  writeFileSync(OUT, moduleText(parts))
  console.log(`▸ contract parts → ${OUT} (css ${parts.css.length}, CCI terms ${parts.cciTerms.length}, StormSafe terms ${parts.ssTerms.length})`)
}
